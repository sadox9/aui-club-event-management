-- AUI Club, Event & Facility Management System
-- Table creation (DDL) and sample data (DML) - PostgreSQL

-- Run with:  psql -v ON_ERROR_STOP=1 -a -f aui_schema_pg.sql -U dhanae 

DROP TABLE IF EXISTS request, equipment, venue, administrator, registration,
                     event_club, event, officer, membership, club, student CASCADE;

-- 1. STUDENT
CREATE TABLE student (
    student_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_name  VARCHAR(50)  NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE
);

-- 2. CLUB
CREATE TABLE club (
    club_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_name  VARCHAR(50) NOT NULL UNIQUE
);

-- 3. MEMBERSHIP (student <-> club, many-to-many)
CREATE TABLE membership (
    student_id  INT  NOT NULL,
    club_id     INT  NOT NULL,
    join_date   DATE NOT NULL,
    PRIMARY KEY (student_id, club_id),
    FOREIGN KEY (student_id) REFERENCES student(student_id) ON DELETE CASCADE,
    FOREIGN KEY (club_id)    REFERENCES club(club_id)       ON DELETE CASCADE
);

-- 4. OFFICER (an officer must be a member of the club)
CREATE TABLE officer (
    officer_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id    INT         NOT NULL,
    club_id       INT         NOT NULL,
    officer_role  VARCHAR(50) NOT NULL,
    FOREIGN KEY (student_id, club_id)
        REFERENCES membership(student_id, club_id) ON DELETE CASCADE
);

-- 5. EVENT
CREATE TABLE event (
    event_id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name             VARCHAR(150) NOT NULL,
    event_date             DATE         NOT NULL,
    created_by_officer_id  INT          NOT NULL,
    FOREIGN KEY (created_by_officer_id) REFERENCES officer(officer_id)
);

-- 6. EVENT_CLUB (event <-> club, many-to-many)
CREATE TABLE event_club (
    event_id  INT NOT NULL,
    club_id   INT NOT NULL,
    PRIMARY KEY (event_id, club_id),
    FOREIGN KEY (event_id) REFERENCES event(event_id) ON DELETE CASCADE,
    FOREIGN KEY (club_id)  REFERENCES club(club_id)   ON DELETE CASCADE
);

-- 7. REGISTRATION (student <-> event, many-to-many)
CREATE TABLE registration (
    student_id         INT  NOT NULL,
    event_id           INT  NOT NULL,
    registration_date  DATE NOT NULL,
    attended           BOOLEAN,
    PRIMARY KEY (student_id, event_id),
    FOREIGN KEY (student_id) REFERENCES student(student_id) ON DELETE CASCADE,
    FOREIGN KEY (event_id)   REFERENCES event(event_id)     ON DELETE CASCADE
);

-- 8. ADMINISTRATOR
CREATE TABLE administrator (
    admin_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_name  VARCHAR(100) NOT NULL
);

-- 9. VENUE
CREATE TABLE venue (
    venue_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_name  VARCHAR(100) NOT NULL UNIQUE,
    capacity    INT NOT NULL CHECK (capacity > 0)
);

-- 10. EQUIPMENT
CREATE TABLE equipment (
    equipment_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_name  VARCHAR(100) NOT NULL UNIQUE,
    total_quantity  INT NOT NULL CHECK (total_quantity >= 0)
);

-- 11. REQUEST (a venue request OR an equipment request)
CREATE TABLE request (
    request_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       INT         NOT NULL,
    request_type   VARCHAR(10) NOT NULL CHECK (request_type IN ('VENUE', 'EQUIPMENT')),
    request_date   DATE        NOT NULL,
    venue_id       INT,
    equipment_id   INT,
    start_time     TIMESTAMP    NOT NULL,
    end_time       TIMESTAMP    NOT NULL,
    quantity       INT CHECK (quantity > 0),
    admin_id       INT,
    decision       VARCHAR(10) CHECK (decision IN ('APPROVED', 'REJECTED')),
    decision_date  DATE,
    CHECK (end_time > start_time),
    CHECK (venue_id IS NULL OR equipment_id IS NULL),   -- never both
    FOREIGN KEY (event_id)     REFERENCES event(event_id)         ON DELETE CASCADE,
    FOREIGN KEY (venue_id)     REFERENCES venue(venue_id),
    FOREIGN KEY (equipment_id) REFERENCES equipment(equipment_id),
    FOREIGN KEY (admin_id)     REFERENCES administrator(admin_id) ON DELETE SET NULL
);


